<?php

// =====================================================================
// ПУНКТ 1. Базовий PHP-скрипт
// =====================================================================

// echo виводить рядок на екран; <br> - перенесення рядка в HTML
echo "<h2>1. Базовий скрипт</h2>";
echo "Hello, World!<br>";


// =====================================================================
// ПУНКТ 2. Змінні та типи даних
// =====================================================================

echo "<h2>2. Змінні та типи даних</h2>";

$stringVar = "Привіт, PHP";   // рядок (string)
$intVar    = 42;              // ціле число (int)
$floatVar  = 3.14;            // число з плаваючою комою (float)
$boolVar   = true;            // булеве значення (bool)

// Виведення значень через echo.
// Примітка: echo true виводить "1", тому для bool використовуємо тернарний оператор.
echo "Рядок: " . $stringVar . "<br>";
echo "Ціле число: " . $intVar . "<br>";
echo "Число з плаваючою комою: " . $floatVar . "<br>";
echo "Булеве значення: " . ($boolVar ? "true" : "false") . "<br>";

// Виведення типу та значення кожної змінної через var_dump.
// <pre> зберігає форматування виводу var_dump у браузері.
echo "<pre>";
var_dump($stringVar);   // string(...) "..."
var_dump($intVar);      // int(42)
var_dump($floatVar);    // float(3.14)
var_dump($boolVar);     // bool(true)
echo "</pre>";


// =====================================================================
// ПУНКТ 3. Конкатенація рядків
// =====================================================================

echo "<h2>3. Конкатенація рядків</h2>";

$str1 = "Hello";
$str2 = "PHP";

// Оператор "." об'єднує рядки. Між змінними додаємо пробіл.
$result = $str1 . " " . $str2;
echo "Результат: " . $result . "<br>";


// =====================================================================
// ПУНКТ 4. Умовні конструкції (if-else)
// =====================================================================

echo "<h2>4. Парне чи непарне число</h2>";

$number = 17;

// Оператор % повертає остачу від ділення.
// Якщо остача від ділення на 2 дорівнює 0 - число парне.
if ($number % 2 == 0) {
    echo "Число $number є парним.<br>";
} else {
    echo "Число $number є непарним.<br>";
}


// =====================================================================
// ПУНКТ 5. Цикли
// =====================================================================

echo "<h2>5. Цикли</h2>";

// Цикл for: числа від 1 до 10
echo "Цикл for (1-10): ";
for ($i = 1; $i <= 10; $i++) {
    echo $i . " ";
}
echo "<br>";

// Цикл while: числа від 10 до 1
echo "Цикл while (10-1): ";
$j = 10;
while ($j >= 1) {
    echo $j . " ";
    $j--;   // зменшуємо лічильник, щоб цикл завершився
}
echo "<br>";


// =====================================================================
// ПУНКТ 6. Масиви
// =====================================================================

echo "<h2>6. Асоціативний масив</h2>";

// Асоціативний масив з інформацією про студента (ключ => значення)
$student = [
    "name"      => "Іван",
    "surname"   => "Петренко",
    "age"       => 20,
    "specialty" => "Комп'ютерні науки"
];

// Виведення кожного елемента масиву за допомогою foreach
echo "<b>Початковий масив:</b><br>";
foreach ($student as $key => $value) {
    echo "$key: $value<br>";
}

// Додавання нового елемента - середнього балу
$student["average_grade"] = 4.7;

// Виведення оновленого масиву
echo "<br><b>Оновлений масив:</b><br>";
foreach ($student as $key => $value) {
    echo "$key: $value<br>";
}

// Додатково: структура масиву через print_r
echo "<pre>";
print_r($student);
echo "</pre>";

?>
